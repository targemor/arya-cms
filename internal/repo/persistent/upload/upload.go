// Package upload implements the Postgres-backed Media Library metadata repository (upload_files).
package upload

import (
	"context"
	"errors"
	"fmt"

	sq "github.com/Masterminds/squirrel"
	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/lucimux/arya/internal/entity"
	"github.com/lucimux/arya/internal/repo"
	"github.com/lucimux/arya/pkg/postgres"
)

const (
	_table = "upload_files"
	// _columns is the full row, in the order scanRow reads it.
	_columns = "id, name, alternative_text, hash, ext, mime, size, url, provider, folder_id, created_at, updated_at"
	// _uniqueViolation is Postgres' unique_violation error code.
	_uniqueViolation = "23505"
	// _foreignKeyViolation is Postgres' foreign_key_violation: a folder_id that no longer exists.
	_foreignKeyViolation = "23503"
)

// Repo -.
type Repo struct {
	*postgres.Postgres
}

// New returns an Upload repository instrumented with OpenTelemetry tracing spans.
func New(pg *postgres.Postgres) repo.UploadRepo {
	return newTraced(&Repo{pg})
}

// Store inserts the file and fills in the ID and timestamps generated by the database.
func (r *Repo) Store(ctx context.Context, file *entity.UploadFile) error {
	sql, args, err := r.Builder.
		Insert(_table).
		Columns("name, alternative_text, hash, ext, mime, size, url, provider, folder_id").
		Values(file.Name, file.AlternativeText, file.Hash, file.Ext, file.Mime, file.Size, file.URL, file.Provider,
			file.FolderID).
		Suffix("RETURNING " + _columns).
		ToSql()
	if err != nil {
		return fmt.Errorf("UploadRepo - Store - r.Builder: %w", err)
	}

	stored, err := scanRow(r.Pool.QueryRow(ctx, sql, args...))
	if err != nil {
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == _uniqueViolation {
			return fmt.Errorf("%w: hash %q already exists", entity.ErrInvalidUpload, file.Hash)
		}

		if errors.As(err, &pgErr) && pgErr.Code == _foreignKeyViolation {
			return entity.ErrFolderNotFound
		}

		return fmt.Errorf("UploadRepo - Store - r.Pool.QueryRow: %w", err)
	}

	*file = stored

	return nil
}

// GetByID -.
func (r *Repo) GetByID(ctx context.Context, id string) (entity.UploadFile, error) {
	if uuid.Validate(id) != nil {
		return entity.UploadFile{}, entity.ErrUploadNotFound
	}

	sql, args, err := r.Builder.Select(_columns).From(_table).Where(sq.Eq{"id": id}).ToSql()
	if err != nil {
		return entity.UploadFile{}, fmt.Errorf("UploadRepo - GetByID - r.Builder: %w", err)
	}

	file, err := scanRow(r.Pool.QueryRow(ctx, sql, args...))
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return entity.UploadFile{}, entity.ErrUploadNotFound
		}

		return entity.UploadFile{}, fmt.Errorf("UploadRepo - GetByID - r.Pool.QueryRow: %w", err)
	}

	return file, nil
}

// List -.
func (r *Repo) List(ctx context.Context, folderID *string, page, pageSize int) ([]entity.UploadFile, int, error) {
	// sq.Eq with a nil value renders "folder_id IS NULL": the root.
	inFolder := sq.Eq{"folder_id": folderID}

	sql, args, err := r.Builder.Select("COUNT(*)").From(_table).Where(inFolder).ToSql()
	if err != nil {
		return nil, 0, fmt.Errorf("UploadRepo - List - count r.Builder: %w", err)
	}

	var total int

	if err = r.Pool.QueryRow(ctx, sql, args...).Scan(&total); err != nil {
		return nil, 0, fmt.Errorf("UploadRepo - List - count r.Pool.QueryRow: %w", err)
	}

	// LIMIT/OFFSET go in as parameters rather than through Limit/Offset, which take uint64.
	sql, args, err = r.Builder.Select(_columns).From(_table).Where(inFolder).
		OrderBy("created_at DESC", "id").
		Suffix("LIMIT ? OFFSET ?", pageSize, (page-1)*pageSize).
		ToSql()
	if err != nil {
		return nil, 0, fmt.Errorf("UploadRepo - List - r.Builder: %w", err)
	}

	rows, err := r.Pool.Query(ctx, sql, args...)
	if err != nil {
		return nil, 0, fmt.Errorf("UploadRepo - List - r.Pool.Query: %w", err)
	}

	files, err := pgx.CollectRows(rows, func(row pgx.CollectableRow) (entity.UploadFile, error) {
		return scanRow(row)
	})
	if err != nil {
		return nil, 0, fmt.Errorf("UploadRepo - List - pgx.CollectRows: %w", err)
	}

	return files, total, nil
}

// CountInFolder -.
func (r *Repo) CountInFolder(ctx context.Context, folderID string) (int, error) {
	sql, args, err := r.Builder.Select("COUNT(*)").From(_table).Where(sq.Eq{"folder_id": folderID}).ToSql()
	if err != nil {
		return 0, fmt.Errorf("UploadRepo - CountInFolder - r.Builder: %w", err)
	}

	var n int

	if err = r.Pool.QueryRow(ctx, sql, args...).Scan(&n); err != nil {
		return 0, fmt.Errorf("UploadRepo - CountInFolder - r.Pool.QueryRow: %w", err)
	}

	return n, nil
}

// Move -.
func (r *Repo) Move(ctx context.Context, id string, folderID *string) (entity.UploadFile, error) {
	if uuid.Validate(id) != nil {
		return entity.UploadFile{}, entity.ErrUploadNotFound
	}

	sql, args, err := r.Builder.Update(_table).
		Set("folder_id", folderID).
		Set("updated_at", sq.Expr("now()")).
		Where(sq.Eq{"id": id}).
		Suffix("RETURNING " + _columns).
		ToSql()
	if err != nil {
		return entity.UploadFile{}, fmt.Errorf("UploadRepo - Move - r.Builder: %w", err)
	}

	file, err := scanRow(r.Pool.QueryRow(ctx, sql, args...))
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return entity.UploadFile{}, entity.ErrUploadNotFound
		}

		// The folder was deleted between the use case's check and this update.
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == _foreignKeyViolation {
			return entity.UploadFile{}, entity.ErrFolderNotFound
		}

		return entity.UploadFile{}, fmt.Errorf("UploadRepo - Move - r.Pool.QueryRow: %w", err)
	}

	return file, nil
}

// Delete -.
func (r *Repo) Delete(ctx context.Context, id string) (entity.UploadFile, error) {
	if uuid.Validate(id) != nil {
		return entity.UploadFile{}, entity.ErrUploadNotFound
	}

	sql, args, err := r.Builder.Delete(_table).Where(sq.Eq{"id": id}).Suffix("RETURNING " + _columns).ToSql()
	if err != nil {
		return entity.UploadFile{}, fmt.Errorf("UploadRepo - Delete - r.Builder: %w", err)
	}

	file, err := scanRow(r.Pool.QueryRow(ctx, sql, args...))
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return entity.UploadFile{}, entity.ErrUploadNotFound
		}

		return entity.UploadFile{}, fmt.Errorf("UploadRepo - Delete - r.Pool.QueryRow: %w", err)
	}

	return file, nil
}

// scanRow reads one row of _columns. Errors are returned as is so callers can match pgx.ErrNoRows
// and wrap with their own method name.
func scanRow(row pgx.Row) (entity.UploadFile, error) {
	var f entity.UploadFile

	err := row.Scan(&f.ID, &f.Name, &f.AlternativeText, &f.Hash, &f.Ext, &f.Mime, &f.Size,
		&f.URL, &f.Provider, &f.FolderID, &f.CreatedAt, &f.UpdatedAt)

	return f, err
}
